3. 앱이 LMS에 로그인하거나 자동으로 다시 로그인하면, 같은 계정으로 PC·웹에 로그인되어 있던 LMS 세션이 끊길 수 있습니다. 동영상 강의를 보는 중이라면 다시 로그인해야 할 수 있습니다.
4. 앱은 학교 서버에 부담을 주지 않도록 정해진 간격과 하루 횟수 안에서만 LMS를 조회합니다. 학교가 요청하거나 LMS가 바뀌면 운영자는 미리 알리지 않고 LMS 연동을 멈출 수 있습니다.

## 제5조 (계획과 정보의 정확성)

1. 앱이 보여 주는 할 일·마감·시간표는 LMS·통합정보시스템에서 마지막으로 불러온 때의 내용입니다. 마감과 제출 여부의 원본은 LMS이므로, 중요한 마감은 LMS에서 직접 확인해 주세요.
2. 앱이 할 일을 빈 시간에 놓는 계획은 제안입니다. 계획을 따를지는 이용자가 정합니다.

## 제6조 (AI 비서)

1. AI 비서는 이용자가 AI 사용에 동의한 경우에만 동작하며, 쓴 문장을 일정·할 일·규칙으로 바꿔 확인 카드로 보여 줍니다. 확인 버튼을 누르기 전에는 저장하지 않습니다.
2. AI가 문장을 잘못 알아들을 수 있습니다. 저장하기 전에 날짜·시각·내용을 확인해 주세요.
3. AI 비서에는 설치당·서비스 전체의 하루 사용 한도가 있습니다. 한도를 넘거나 AI를 쓸 수 없을 때는 직접 추가로 넣을 수 있습니다.
4. AI 비서에 다른 사람의 개인정보나 민감한 정보를 쓰지 말아 주세요.

## 제7조 (금지 행위)

이용자는 다음을 해서는 안 됩니다.

1. 다른 사람의 계정으로 로그인하는 일
2. 앱이나 운영자의 서버를 고쳐 쓰거나 자동으로 반복 호출해 학교 서버나 운영자의 서버에 부담을 주는 일
3. AI 비서로 법이나 Anthropic의 이용 정책에 어긋나는 내용을 만들려는 일

## 제8조 (서비스의 변경과 중단)

운영자는 학생 프로젝트로 앱을 운영하므로, 기능을 바꾸거나 앱의 전부 또는 일부를 멈출 수 있습니다. 미리 알릴 수 있으면 이 페이지와 앱으로 알립니다.

## 제9조 (책임의 제한)

1. 운영자는 앱을 있는 그대로 제공하며, 앱이 오류 없이 늘 동작하거나 모든 마감을 알려 준다고 보증하지 않습니다.
2. 운영자의 고의나 중대한 과실이 없는 한, 앱의 오류·중단, LMS 정보의 늦음이나 틀림, AI의 잘못된 해석 때문에 생긴 손해(마감을 놓친 경우 등)에 책임을 지지 않습니다.
3. 학교 정보시스템의 장애나 정책 변경 때문에 생긴 문제는 운영자가 책임지지 않습니다.

